#!/usr/bin/env bash
# Prototype driver (branch neighbour-hmm): call tomato1 under several depth conditions,
# keeping each record's per-sample likelihood rows (PVC_PROTOTYPE_ROWS).
# Runs inside the dev container. Usage: run_conditions.sh <step>
set -euo pipefail
WT=/Users/jose/devel/pop_var_caller-neighbour-hmm
T1=/Users/jose/devel/pop_var_caller/benchmarks/tomato1
REF=/Users/jose/genomes/s_lycopersicum/4.00/S_lycopersicum_chromosomes.4.00.fa
CAT=$WT/tmp/tomato/S_lycopersicum_chromosomes.4.00.repeats.parquet
BED=$T1/regions.bed
PVC=$WT/target-container/release/pvc
OUT=$WT/tmp/tomato
COUNTS=$WT/tmp/tomato1_readcounts.txt
# The nine accessions at 18x or more: the held-out truth set.
DEEP=$(awk '$2*150/8e6 >= 18 {sub(/\.bench\.cram/,"",$1); print $1}' "$COUNTS")

downsample() { # <target depth> <dir> [deep-only]
    local target=$1 dir=$2 only=${3:-}
    mkdir -p "$dir"
    while read -r f n; do
        local base=${f%.bench.cram}
        if [[ -n "$only" ]] && ! grep -qx "$base" <<<"$DEEP"; then
            ln -sf "$T1/crams_nobaq/$f" "$dir/$f"; ln -sf "$T1/crams_nobaq/$f.crai" "$dir/$f.crai"; continue
        fi
        local frac
        frac=$(awk -v n="$n" -v t="$target" 'BEGIN{d=n*150/8e6; f=t/d; if (f>=1) print "keep"; else printf "%.4f", f}')
        if [[ $frac == keep ]]; then
            ln -sf "$T1/crams_nobaq/$f" "$dir/$f"; ln -sf "$T1/crams_nobaq/$f.crai" "$dir/$f.crai"
        else
            samtools view -T "$REF" -C -s "7${frac#0}" -o "$dir/$f" "$T1/crams_nobaq/$f"
            samtools index "$dir/$f"
        fi
    done < "$COUNTS"
}

psps() { # <cram dir> <psp dir>
    mkdir -p "$2"
    for c in "$1"/*.bench.cram; do
        local base; base=$(basename "$c" .bench.cram)
        [[ -f "$2/$base.psp" ]] && continue
        "$PVC" generate-psps --quiet --reference "$REF" --catalog "$CAT" --regions "$BED" \
            --alignment "$c" --output-dir "$2"
    done
}

call() { # <name> <psp...>
    local name=$1; shift
    local args=() p
    # Six plants were sequenced twice (same SM tag); a cohort holds each once. Where one run
    # of the pair is a deep accession, that one is kept.
    for p in "$@"; do
        [[ $p =~ SRR7279(484|515|535|488|529|539) ]] || args+=(--psp "$p")
    done
    mkdir -p "$OUT/calls"
    "$PVC" estimate-parameters --quiet --force --reference "$REF" --catalog "$CAT" "${args[@]}" \
        --threads "${THREADS:-6}" --output "$OUT/calls/$name.parameters.toml"
    PVC_PROTOTYPE_ROWS="$OUT/calls/$name.rows.tsv" "$PVC" call-from-psps --quiet --force \
        --reference "$REF" --catalog "$CAT" "${args[@]}" --threads "${THREADS:-6}" \
        --parameters "$OUT/calls/$name.parameters.toml" --output "$OUT/calls/$name.vcf"
}

case "$1" in
    downsample)
        downsample 3 "$OUT/crams_deep3" only
        downsample 3 "$OUT/crams_all3"
        downsample 1 "$OUT/crams_all1"
        downsample 1 "$OUT/crams_deep1" only ;;
    psps)
        echo "psps are generated by psps_parallel.sh" ;;
    call_one)
        call "$2" "$OUT"/psp_$2/*/*.psp ;;
    deep_psps) # <deep3|deep1>: psps for the downsampled nine, links to psp_full for the rest
        mkdir -p "$OUT/psp_$2"
        for c in "$OUT/crams_$2"/*.bench.cram; do
            base=$(basename "$c" .bench.cram)
            if [[ -L "$c" ]]; then
                [[ -e "$OUT/psp_$2/$base" ]] || ln -s "$OUT/psp_full/$base" "$OUT/psp_$2/$base"
            elif ! ls "$OUT/psp_$2/$base"/*.psp >/dev/null 2>&1; then
                "$PVC" generate-psps --quiet --reference "$REF" --catalog "$CAT" --regions "$BED" \
                    --alignment "$c" --output-dir "$OUT/psp_$2/$base"
            fi
        done ;;
    call)
        for d in full deep3 all3 all1 deep1; do
            [[ -f "$OUT/calls/$d.vcf" ]] || call "$d" "$OUT"/psp_$d/*/*.psp
        done ;;
    single)
        for s in $DEEP; do
            for d in deep3 deep1; do
                [[ -f "$OUT/calls/single_${d}_$s.vcf" ]] || call "single_${d}_$s" "$OUT"/psp_$d/$s/*.psp
            done
        done ;;
    *) echo "unknown step $1" >&2; exit 2 ;;
esac
